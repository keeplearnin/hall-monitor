"""Record the current manifests and prompts as approved.

    uv run python -m hall_monitor.approvals

    uv run python -m hall_monitor.approvals --resume STOP_ID   # restart a stopped agent

Writes registry/approvals.yaml. Run it only as part of a reviewed change: the diff to that file
is the approval. The registry refuses any manifest whose digest isn't in it, and a test fails
if a manifest or prompt changes and this file isn't regenerated. A prompt change also needs a
new PROMPT_VERSION (and a manifest change a new version): that is a review rule, not checked by
a test. Stops already cleared are kept; --resume clears one more, so restarting a stopped agent
is reviewed like any approval.
"""

from __future__ import annotations

import argparse
import hashlib
from types import ModuleType

import yaml

from hall_monitor.agents import coverage_check, critic, intake, recommendation, risk_fraud
from hall_monitor.complaints import triage_agent
from hall_monitor.hr import leave_explainer, leave_intake
from hall_monitor.kill_switch import STOPS_FILENAME, load_stops
from hall_monitor.registry import (
    APPROVALS_FILENAME,
    DEFAULT_REGISTRY_DIR,
    NON_MANIFEST_FILES,
    AgentManifest,
    check_no_send,
    load_approvals,
)

CLAIMS_MODULES = (intake, coverage_check, risk_fraud, critic, recommendation)
HR_MODULES = (leave_intake, leave_explainer)
COMPLAINT_MODULES = (triage_agent,)
CLAIMS_AGENTS = tuple(m.AGENT_ID for m in CLAIMS_MODULES)
AGENT_MODULES: dict[str, ModuleType] = {
    m.AGENT_ID: m for m in CLAIMS_MODULES + HR_MODULES + COMPLAINT_MODULES
}


def prompt_sha256(module: ModuleType) -> str:
    """Hash of the agent's system prompt template, before the policy wording is filled in."""
    return hashlib.sha256(module.SYSTEM_PROMPT.encode()).hexdigest()


def current_approvals(
    previous: dict[str, dict] | None = None,
    resume: dict[str, str] | None = None,
    manifests: list[AgentManifest] | None = None,
) -> dict[str, dict]:
    """Approvals for the current manifests and prompts.

    previous (default: the approvals file) supplies stops already cleared, which are kept;
    resume maps an agent ID to one more stop to clear. manifests defaults to those in the
    registry directory. A manifest granting any tool that could send is never approved (HM-25).
    """
    if previous is None:
        previous = load_approvals()
    resume = resume or {}
    agents = {}
    for manifest in manifests if manifests is not None else _manifests():
        check_no_send(manifest)
        entry = {"manifest_digest": manifest.digest(), "version": manifest.version}
        module = AGENT_MODULES.get(manifest.id)
        if module is not None:
            entry["prompt_version"] = module.PROMPT_VERSION
            entry["prompt_sha256"] = prompt_sha256(module)
        cleared = list(previous.get(manifest.id, {}).get("cleared_stops", []))
        if manifest.id in resume and resume[manifest.id] not in cleared:
            cleared.append(resume[manifest.id])
        if cleared:
            entry["cleared_stops"] = cleared
        agents[manifest.id] = entry
    return agents


def _resume(stop_id: str) -> dict[str, str]:
    for stop in load_stops(DEFAULT_REGISTRY_DIR / STOPS_FILENAME).stops:
        if stop.id == stop_id:
            return {stop.agent: stop.id}
    raise SystemExit(f"no stop {stop_id} in {STOPS_FILENAME}")


def _manifests():
    for file in sorted(DEFAULT_REGISTRY_DIR.glob("*.yaml")):
        if file.name not in NON_MANIFEST_FILES:
            yield AgentManifest.model_validate(yaml.safe_load(file.read_text()))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(prog="python -m hall_monitor.approvals")
    parser.add_argument("--resume", metavar="STOP_ID", help="clear a stop, restarting its agent")
    args = parser.parse_args()
    header = (
        "# Approved hall passes. Generated by `uv run python -m hall_monitor.approvals`;\n"
        "# a change to this file is an approval and should be reviewed as one.\n"
    )
    body = yaml.safe_dump(
        {"agents": current_approvals(resume=_resume(args.resume) if args.resume else None)},
        sort_keys=True,
    )
    (DEFAULT_REGISTRY_DIR / APPROVALS_FILENAME).write_text(header + body)
